enum LayoutType {
  saas,
  portfolio,
  ecommerce,
  restaurant,
  dashboard,
  agency,
  education,
  entertainment,
  productLaunch,
}

class SectionSpec {
  final String id;
  final String title;
  final String description;
  final String
  type; // hero, features, showcase3d, pricing, testimonials, gallery, contact
  final Map<String, dynamic> data;

  const SectionSpec({
    required this.id,
    required this.title,
    required this.description,
    required this.type,
    this.data = const {},
  });

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'title': title,
      'description': description,
      'type': type,
      'data': data,
    };
  }

  factory SectionSpec.fromJson(Map<String, dynamic> json) {
    return SectionSpec(
      id: json['id'] as String? ?? 'section',
      title: json['title'] as String? ?? '',
      description: json['description'] as String? ?? '',
      type: json['type'] as String? ?? 'features',
      data: (json['data'] as Map<String, dynamic>?) ?? {},
    );
  }
}

class WebsiteSpecification {
  final String title;
  final String tagline;
  final LayoutType layoutType;
  final String primaryColor;
  final String secondaryColor;
  final String backgroundColor;
  final String textColor;
  final bool enable3DEffects;
  final List<SectionSpec> sections;
  final List<String> navigationLinks;

  const WebsiteSpecification({
    required this.title,
    required this.tagline,
    required this.layoutType,
    required this.primaryColor,
    required this.secondaryColor,
    required this.backgroundColor,
    required this.textColor,
    required this.enable3DEffects,
    required this.sections,
    required this.navigationLinks,
  });

  Map<String, dynamic> toJson() {
    return {
      'title': title,
      'tagline': tagline,
      'layoutType': layoutType.name,
      'primaryColor': primaryColor,
      'secondaryColor': secondaryColor,
      'backgroundColor': backgroundColor,
      'textColor': textColor,
      'enable3DEffects': enable3DEffects,
      'sections': sections.map((s) => s.toJson()).toList(),
      'navigationLinks': navigationLinks,
    };
  }

  factory WebsiteSpecification.fromJson(Map<String, dynamic> json) {
    return WebsiteSpecification(
      title: json['title'] as String? ?? 'Cyber AI Project',
      tagline: json['tagline'] as String? ?? 'Generated by Cyber AI',
      layoutType: LayoutType.values.firstWhere(
        (e) => e.name == json['layoutType'],
        orElse: () => LayoutType.saas,
      ),
      primaryColor: json['primaryColor'] as String? ?? '#00f0ff',
      secondaryColor: json['secondaryColor'] as String? ?? '#8b5cf6',
      backgroundColor: json['backgroundColor'] as String? ?? '#070b14',
      textColor: json['textColor'] as String? ?? '#f8fafc',
      enable3DEffects: (json['enable3DEffects'] as bool?) ?? true,
      sections:
          (json['sections'] as List<dynamic>?)
              ?.map((s) => SectionSpec.fromJson(s as Map<String, dynamic>))
              .toList() ??
          [],
      navigationLinks:
          (json['navigationLinks'] as List<dynamic>?)
              ?.map((n) => n.toString())
              .toList() ??
          ['Home', 'Features', 'Showcase', 'Contact'],
    );
  }
}
